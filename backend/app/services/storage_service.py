async def read_upload_limited(upload: UploadFile, max_bytes: int | None = None) -> bytes:
    """Read an upload in chunks, aborting with 413 as soon as it exceeds ``max_bytes``."""
    limit = settings.max_upload_size_bytes if max_bytes is None else max_bytes
    chunks: list[bytes] = []
    total = 0
    while True:
        chunk = await upload.read(_READ_CHUNK_SIZE)
        if not chunk:
            break
        total += len(chunk)
        if total > limit:
            raise PayloadTooLargeError(
                f"File is too large (maximum {limit // (1024 * 1024)} MB)"
                if limit >= 1024 * 1024
                else f"File is too large (maximum {limit} bytes)"
            )
        chunks.append(chunk)
    if total == 0:
        raise BadRequestError("The uploaded file is empty")
    return b"".join(chunks)


def validate_image(data: bytes, filename: str | None) -> ImageType:
    """Validate an image by magic bytes AND filename extension.

    Only PNG, JPEG and WebP are accepted. SVG is rejected because it can carry scripts.

    Raises:
        BadRequestError: if the type is unsupported or the extension does not match.
    """
    suffix = Path(filename or "").suffix.lower()
    if suffix == ".svg" or suffix == ".svgz":
        raise BadRequestError("SVG images are not supported. Please upload a PNG, JPEG or WebP.")

    kind = filetype.guess(data)
    image_type = ALLOWED_IMAGE_TYPES.get(kind.mime) if kind is not None else None
    if image_type is None:
        raise BadRequestError("Unsupported file type. Please upload a PNG, JPEG or WebP image.")
    if suffix not in image_type.allowed_extensions:
        raise BadRequestError("The file extension does not match the file contents.")
    return image_type


def safe_display_filename(filename: str | None, fallback: str) -> str:
    """Return a display-safe version of a user-supplied filename (no paths, ≤ 255 chars)."""
    name = Path((filename or "").replace("\\", "/")).name
    name = re.sub(r"[\x00-\x1f\x7f\"]", "", name).strip()
    if not name or name.startswith("."):
        return fallback
    if len(name) > 255:
        stem, dot, ext = name.rpartition(".")
        name = f"{stem[: 255 - len(ext) - 1]}.{ext}" if dot and len(ext) <= 10 else name[:255]
    return name
