def logo_public_url(file: FileUpload | None) -> str | None:
    """Return the API-relative public URL of a logo, or ``None`` when there is no logo."""
    if file is None:
        return None
    return f"{PUBLIC_FILES_PATH}/{file.storage_path}"


def read_file_bytes(file: FileUpload) -> bytes:
    """Return the stored bytes of ``file`` (raises ``FileNotFoundError`` if missing)."""
    return get_storage().read(file.storage_path)


def delete_stored_file(key: str) -> None:
    """Best-effort delete of a stored object; failures are logged, not raised."""
    try:
        get_storage().delete(key)
    except (StorageError, ValueError, OSError):
        logger.warning("Failed to delete stored file %s", key, exc_info=True)


def is_valid_storage_key(key: str) -> bool:
    """Whether ``key`` has the exact shape produced by :func:`generate_storage_key`."""
    return STORAGE_KEY_PATTERN.fullmatch(key) is not None


def generate_storage_key(extension: str) -> str:
    """Return a new random, unguessable storage key such as ``<32 hex>.png``."""
    return f"{uuid.uuid4().hex}{extension}"


