"""Pluggable file storage (local disk or S3) and upload validation helpers.

Storage keys are random ``uuid4().hex + ext`` names generated by :func:`generate_storage_key`;
user-supplied filenames are never used as keys. Logos are served publicly through
``GET /api/v1/files/public/{key}`` (see :func:`logo_public_url`), relying on the key being
unguessable.

SVG uploads are deliberately rejected: an SVG can embed scripts and would be served from the
API origin, which would enable stored XSS.
"""

from __future__ import annotations

import logging
import re
import uuid
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

import filetype
from fastapi import UploadFile, status

from app.config import settings
from app.exceptions import AppError, BadRequestError

if TYPE_CHECKING:
    from app.models import FileUpload

logger = logging.getLogger(__name__)

PUBLIC_FILES_PATH = "/api/v1/files/public"
_READ_CHUNK_SIZE = 64 * 1024

# Generic key shape accepted by the storage backends (defence in depth against traversal).
_SAFE_KEY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,254}$")


@dataclass(frozen=True)
class ImageType:
    """An accepted image format."""

    content_type: str
    extension: str  # canonical extension used for the storage key (with dot)
    allowed_extensions: frozenset[str]  # accepted extensions of the original filename


ALLOWED_IMAGE_TYPES: dict[str, ImageType] = {
    "image/png": ImageType("image/png", ".png", frozenset({".png"})),
    "image/jpeg": ImageType("image/jpeg", ".jpg", frozenset({".jpg", ".jpeg"})),
    "image/webp": ImageType("image/webp", ".webp", frozenset({".webp"})),
}

# Strict format of keys created by this module: 32 lowercase hex chars + allowed extension.
STORAGE_KEY_PATTERN = re.compile(r"^[0-9a-f]{32}\.(?:png|jpg|webp)$")


class PayloadTooLargeError(AppError):
    """413 - the uploaded file exceeds the configured size limit."""

    status_code = status.HTTP_413_REQUEST_ENTITY_TOO_LARGE
    default_detail = "File is too large"


class StorageError(Exception):
    """Raised when the storage backend fails unexpectedly."""


# ---------------------------------------------------------------------------
# Backends
# ---------------------------------------------------------------------------


class StorageBackend(Protocol):
    """Minimal blob storage interface."""

    def save(self, data: bytes, key: str, content_type: str) -> None:
        """Store ``data`` under ``key``."""
        ...

    def read(self, key: str) -> bytes:
        """Return the bytes stored under ``key``; raise ``FileNotFoundError`` if missing."""
        ...

    def delete(self, key: str) -> None:
        """Delete ``key``; deleting a missing key is not an error."""
        ...


def _check_key(key: str) -> None:
    """Reject keys that could escape the storage root or are otherwise malformed."""
    if not _SAFE_KEY_PATTERN.fullmatch(key) or ".." in key:
        raise ValueError(f"Invalid storage key: {key!r}")


class LocalStorage:
    """Stores files in a directory on the local filesystem (``settings.UPLOAD_DIR``)."""

    def __init__(self, root: str | Path | None = None) -> None:
        self.root = Path(root if root is not None else settings.UPLOAD_DIR).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path_for(self, key: str) -> Path:
        """Return the absolute path for ``key``, refusing anything outside the root."""
        _check_key(key)
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root) or path == self.root:
            raise ValueError(f"Invalid storage key: {key!r}")
        return path

    def save(self, data: bytes, key: str, content_type: str) -> None:
        """Write ``data`` atomically (temp file + rename)."""
        path = self._path_for(key)
        tmp_path = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        try:
            tmp_path.write_bytes(data)
            tmp_path.replace(path)
        except OSError as exc:
            tmp_path.unlink(missing_ok=True)
            raise StorageError(f"Could not write file {key}") from exc

    def read(self, key: str) -> bytes:
        """Read the file stored under ``key``."""
        path = self._path_for(key)
        if not path.is_file():
            raise FileNotFoundError(key)
        return path.read_bytes()

    def delete(self, key: str) -> None:
        """Remove the file stored under ``key`` if it exists."""
        self._path_for(key).unlink(missing_ok=True)


class S3Storage:
    """Stores files in an S3-compatible bucket (boto3 is imported lazily)."""

    def __init__(self) -> None:
        import boto3  # lazy: optional dependency, only needed for S3

        kwargs: dict[str, Any] = {}
        if settings.S3_ENDPOINT_URL:
            kwargs["endpoint_url"] = settings.S3_ENDPOINT_URL
        if settings.S3_ACCESS_KEY_ID and settings.S3_SECRET_ACCESS_KEY:
            kwargs["aws_access_key_id"] = settings.S3_ACCESS_KEY_ID
            kwargs["aws_secret_access_key"] = settings.S3_SECRET_ACCESS_KEY
        self.bucket = settings.S3_BUCKET
        self._client: Any = boto3.client("s3", **kwargs)

    def save(self, data: bytes, key: str, content_type: str) -> None:
        """Upload ``data`` to ``bucket/key``."""
        _check_key(key)
        try:
            self._client.put_object(
                Bucket=self.bucket, Key=key, Body=data, ContentType=content_type
            )
        except Exception as exc:
            raise StorageError(f"Could not upload file {key}") from exc

    def read(self, key: str) -> bytes:
        """Download ``bucket/key``."""
        _check_key(key)
        try:
            response = self._client.get_object(Bucket=self.bucket, Key=key)
        except self._client.exceptions.NoSuchKey as exc:
            raise FileNotFoundError(key) from exc
        except Exception as exc:
            raise StorageError(f"Could not read file {key}") from exc
        body: bytes = response["Body"].read()
        return body

    def delete(self, key: str) -> None:
        """Delete ``bucket/key`` (S3 treats missing keys as success)."""
        _check_key(key)
        try:
            self._client.delete_object(Bucket=self.bucket, Key=key)
        except Exception as exc:
            raise StorageError(f"Could not delete file {key}") from exc


@lru_cache
def get_storage() -> StorageBackend:
    """Return the configured storage backend (cached; selected by ``STORAGE_BACKEND``)."""
    if settings.STORAGE_BACKEND == "s3":
        return S3Storage()
    return LocalStorage()


